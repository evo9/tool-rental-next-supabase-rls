-- =====================================================================
-- Проверка чистой функции public.calc_rental_amount(): только
-- арифметика, без ролей, RLS и таблиц - функция immutable и не читает
-- ничего, кроме своих аргументов.
--
-- Предусловия: миграция 20260923152927_pricing_and_overdue.sql
--   применена. Ролей и фикстур не требуется - вызов идёт от текущей
--   роли (postgres в psql/SQL Editor), которая имеет права владельца
--   и не зависит от grant/revoke execute.
-- Запуск:
--   SQL Editor: вставить целиком, Run. Дошёл до конца = всё прошло,
--     провал останавливает скрипт с текстом FAIL.
--   psql "$DB_URL" -f tests/pricing/05_calc.sql - видны NOTICE по
--     каждому сценарию.
-- В базе ничего не остаётся: всё внутри begin; ... rollback;.
-- =====================================================================
begin;

-- Сравнивает результат calc_rental_amount с ожиданием по всем трём
-- колонкам сразу - несовпадение любой из них печатает все шесть чисел,
-- этого достаточно, чтобы понять, что именно разошлось, без второго
-- прогона с отладочным SELECT.
create function pg_temp.expect_calc(
    p_label        text,
    p_rate         numeric,
    p_issued       timestamptz,
    p_planned      timestamptz,
    p_returned     timestamptz,
    p_grace_hours  int,
    p_base_days    int,
    p_overdue_days int,
    p_amount       numeric
) returns void
    language plpgsql as $$
declare
  v record;
begin
  select * into v
  from public.calc_rental_amount(p_rate, p_issued, p_planned, p_returned, p_grace_hours);

  if v.base_days is distinct from p_base_days
     or v.overdue_days is distinct from p_overdue_days
     or v.amount is distinct from p_amount then
    raise exception 'FAIL [%]: ожидалось (base=%, overdue=%, amount=%), получено (base=%, overdue=%, amount=%)',
      p_label, p_base_days, p_overdue_days, p_amount, v.base_days, v.overdue_days, v.amount;
  end if;

  raise notice 'ok [%] base_days=% overdue_days=% amount=%', p_label, v.base_days, v.overdue_days, v.amount;
end $$;

-- 1. Возврат через 10 минут после выдачи, план далеко впереди -
--    минимум одни сутки, даже если фактически прошли считанные минуты.
select pg_temp.expect_calc(
  '1: 10 минут после выдачи',
  100, '2026-01-01T00:00:00Z', '2026-01-11T00:00:00Z', '2026-01-01T00:10:00Z', 0,
  1, 0, 100);

-- 2. План 24 ч, возврат ровно через 24 ч - ровно одни сутки, просрочки
--    нет: least(returned, planned) = обе границы совпадают.
select pg_temp.expect_calc(
  '2: возврат ровно по плану через 24ч',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T00:00:00Z', 0,
  1, 0, 100);

-- 3. План 24 ч, возврат на минуту позже, grace 0 - началась вторая
--    сутки просрочки сразу же, минимум одна начатая сутки просрочки.
select pg_temp.expect_calc(
  '3: план 24ч, просрочка 1 минута, grace 0',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T00:01:00Z', 0,
  1, 1, 200);

-- 4. Возврат минута в минуту по плану, grace положительный - просрочки
--    нет независимо от grace: разница по времени и так нулевая.
select pg_temp.expect_calc(
  '4: возврат минута в минуту по плану, grace 5ч',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T00:00:00Z', 5,
  1, 0, 100);

-- 5. Просрочка 2 ч при grace 3 ч - в пределах grace, не считается.
select pg_temp.expect_calc(
  '5: просрочка 2ч, grace 3ч',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T02:00:00Z', 3,
  1, 0, 100);

-- 6. Просрочка ровно 3 ч при grace 3 ч - граница включительно, ещё
--    не считается (overdue = greatest(0, 0) = 0).
select pg_temp.expect_calc(
  '6: просрочка ровно 3ч, grace 3ч',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T03:00:00Z', 3,
  1, 0, 100);

-- 7. Просрочка на минуту больше grace - начата одна сутки просрочки.
select pg_temp.expect_calc(
  '7: просрочка 3ч1мин, grace 3ч',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-02T03:01:00Z', 3,
  1, 1, 200);

-- 8. Просрочка 25 ч без grace - две начатые сутки просрочки
--    (25ч > 24ч, начата вторая).
select pg_temp.expect_calc(
  '8: просрочка 25ч, grace 0',
  100, '2026-01-01T00:00:00Z', '2026-01-02T00:00:00Z', '2026-01-03T01:00:00Z', 0,
  1, 2, 300);

-- 9. План 3 суток, возврат раньше - через 1 сутки 2 ч. Платятся
--    фактические сутки (не по плану), просрочки нет вообще, потому что
--    возврат раньше плана.
select pg_temp.expect_calc(
  '9: план 3 суток, возврат раньше через 1 сутки 2ч',
  100, '2026-01-01T00:00:00Z', '2026-01-04T00:00:00Z', '2026-01-02T02:00:00Z', 0,
  2, 0, 200);

-- 10. Копейки: тариф 99.99, 3 полных суток без просрочки -
--     299.97, округление до копеек не искажает точное произведение.
select pg_temp.expect_calc(
  '10: копейки, тариф 99.99, 3 суток',
  99.99, '2026-01-01T00:00:00Z', '2026-01-11T00:00:00Z', '2026-01-04T00:00:00Z', 0,
  3, 0, 299.97);

rollback;
