-- =====================================================================
-- Ручная проверка этапа 8: намеренно сломать одну политику.
--
-- Что делает:
--   Пересоздаёт политику "tools: manager+ inserts" на public.tools с
--   ошибкой: вместо "роль >= MANAGER" условие WITH CHECK пропускает любого
--   активного сотрудника. Ожидаемое поведение после этого скрипта:
--   OPERATOR может добавить модель инструмента.
--
-- ВНИМАНИЕ: база облачная и общая. Скрипт меняет её сразу, миграцией это
--   не откатить. Сразу после проверки запустить restore-policy.sql.
--
-- Как использовать:
--   1. psql "$DB_URL" -v ON_ERROR_STOP=1 -f tests/manual/break-policy.sql
--   2. npm run test:api
--      Ожидание: прогон падает ровно на одной ячейке: tools.insert,
--      OPERATOR - ожидалось error:42501, получено allowed. Остальные
--      ячейки совпадают (у деактивированного оператора и anon отказ
--      остаётся, потому что там срабатывает другой слой).
--      Модель, которую матрица создала под оператором, уберёт cleanup
--      прогона (SUPERADMIN удаляет модели с префиксом __matrix-).
--   3. psql "$DB_URL" -v ON_ERROR_STOP=1 -f tests/manual/restore-policy.sql
--   4. npm run test:api - снова без расхождений.
--
-- Почему это ловит именно матрица, а не тест по описанию: она делает
-- настоящий запрос настоящей сессией оператора и сравнивает ответ с
-- ожиданием, записанным в tests/api/matrix.ts.
-- =====================================================================

drop policy if exists "tools: manager+ inserts" on public.tools;

-- Ошибка: is not null вместо >= 'MANAGER' - проверяется только то, что
-- вызывающий сотрудник, а не его роль.
create policy "tools: manager+ inserts"
on public.tools for insert
to authenticated
with check ((select public.current_staff_role()) is not null);
