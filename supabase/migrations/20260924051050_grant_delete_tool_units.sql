-- =====================================================================
-- Этап 8. Грант DELETE на tool_units, забытый на этапе 4
--
-- Что делает:
--   Выдаёт роли authenticated право DELETE на public.tool_units. Роль по
--   строке по-прежнему решает политика "superadmin can delete tool units".
--
-- Зависит от:
--   20260923120539_tool_units_and_rentals.sql - таблица, RLS и политика
--   DELETE "superadmin can delete tool units".
--
-- Зачем: матрица прав через настоящий API (tests/api, этап 8) показала
--   расхождение: SUPERADMIN, удаляющий ни разу не выданную единицу,
--   получал 42501, хотя политика и docs/roles.md обещали успех. В миграции
--   этапа 4 политика DELETE есть, а гранта DELETE нет: две проверки стоят
--   друг за другом (сначала грант, потом политика), и без первой вторая
--   никогда не выполняется. Политика была мёртвой, а SQL-тесты этого не
--   видели, потому что удаление единицы в них не проверялось. Новая
--   миграция, а не правка исходной: она уже применена (CLAUDE.md).
--   Идемпотентно: grant можно выполнять повторно.
--
-- Что даёт после миграции:
--   SUPERADMIN - удаляет единицу, которую ни разу не выдавали.
--   MANAGER, OPERATOR, деактивированный - 0 строк (USING политики не
--     пропускает строку, ошибки нет).
--   anon - 42501: гранта нет, отзыв revoke all от этапа 4 остаётся в силе.
--   Единица, которая хоть раз была в аренде, не удаляется никем: внешний
--     ключ rental_items.tool_unit_id (on delete restrict) даёт 23503.
--
-- Как проверить:
--   psql "$DB_URL" -f tests/policies/08_tool_units_delete.sql
--   npm run test:api - строка tool_units.delete без расхождений.
-- =====================================================================

grant delete on public.tool_units to authenticated;
