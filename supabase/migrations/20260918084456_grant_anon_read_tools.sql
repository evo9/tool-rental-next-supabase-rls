-- Демонстрация двух слоёв доступа.
-- GRANT отвечает на вопрос "есть ли у роли право трогать таблицу",
-- RLS - "какие строки она увидит". Без этого grant роль anon получала
-- permission denied и до политик дело не доходило.
-- После него anon проходит первый слой, но политики для него нет,
-- поэтому select возвращает пустой массив со статусом 200.
grant select on public.tools to anon;