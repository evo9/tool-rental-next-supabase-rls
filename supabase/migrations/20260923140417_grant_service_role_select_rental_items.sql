-- =====================================================================
-- Дополнительный грант SELECT на rental_items для service_role
--
-- Что делает: добавляет service_role привилегию select на
--   public.rental_items.
--
-- Зависит от: 20260923120539_tool_units_and_rentals.sql (tool_units,
--   rental_items, tool_units_guard_status).
--
-- Зачем: тот же урок, что и в 20260918162404_grant_service_role_select_staff.sql
--   на этапе 2, только на этот раз найден при первом же повторном
--   запуске сида, а не после отправки в прод. npm run seed:staff делает
--   upsert по tool_units.inventory_number. Postgres формирует
--   ON CONFLICT DO UPDATE со всеми колонками payload, включая status,
--   даже если значение не меняется, - "update of status" срабатывает
--   по факту наличия колонки в SET, а не по факту изменения значения.
--   Триггер tool_units_guard_status (security invoker, то есть выполняется
--   с правами service_role) читает rental_items, чтобы решить, допустим
--   ли переход, - без этого гранта чтение падает с 42501 раньше, чем
--   триггер успевает решить, что переход на самом деле никакой (AVAILABLE
--   в AVAILABLE), и упасть было не должно.
--   Отдельной миграцией, а не правкой предыдущей: та уже отправлена
--   в облако через db push, повторно она не выполнится (grant сам по
--   себе идемпотентен, но здесь это добавление нового гранта, которого
--   в исходном файле не было, а не правка содержимого существующего -
--   тот же выбор, что и в истории со staff на этапе 2).
--
-- Как проверить:
--   npm run seed:staff - два прогона подряд без ошибок (вставка,
--   затем обновление существующих единиц).
--   Негатив: select has_table_privilege('service_role', 'public.staff', 'DELETE');
--   -> false (грант остаётся точечным, не revoke all/grant all).
-- =====================================================================

grant select on public.rental_items to service_role;
