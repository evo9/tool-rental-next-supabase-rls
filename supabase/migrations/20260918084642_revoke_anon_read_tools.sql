-- =============================================================================
-- Отзыв прав чтения tools у роли anon
--
-- Что делает: снимает право select на public.tools с роли anon.
--
-- Зависит от: 20260918084456_grant_anon_read_tools.sql, который это право выдал.
--
-- Зачем: предыдущая миграция выдавала grant специально, чтобы увидеть работу
-- RLS в чистом виде - anon проходил проверку прав, но не находил подходящей
-- политики и получал 200 с пустым массивом. Демонстрация выполнена, результат
-- записан в docs/rls-notes.md. Рабочее состояние проекта другое: неавторизо-
-- ванный доступ к данным точки проката не нужен вообще, поэтому anon отсекается
-- на первом слое, правами, не доходя до политик. Два независимых слоя надёжнее
-- одного: если политику когда-нибудь ошибочно расширят до `to public`, anon всё
-- равно не пройдёт дальше grant.
--
-- Как проверить:
--   curl -i "https://<ref>.supabase.co/rest/v1/tools?select=*" \
--     -H "apikey: <publishable>" -H "Authorization: Bearer <publishable>"
--   Ожидается: 401, код 42501, permission denied for table tools.
--
--   Тот же запрос с access token сотрудника возвращает 200 и строки:
--   у роли authenticated grant остался, политика на select тоже.
-- =============================================================================

revoke select on public.tools from anon;